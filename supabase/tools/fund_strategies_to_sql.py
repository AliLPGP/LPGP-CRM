#!/usr/bin/env python3
"""
Turn fund-strategy research (data/fund-strategies/*.json) into one idempotent
loader per file in supabase/fund-strategies/: every fund of a family with a
strategy gets fund_details.strategy_code, and the page that states it (url,
name, kind, the phrase, and whether it describes the series or a
single-strategy manager) under fund_details.sources.strategy_code. A family
with no strategy writes nothing. Keys outside strategies.ts's strategy axis,
and verdicts without a URL or a phrase, are refused.

    python3 supabase/tools/fund_strategies_to_sql.py data/fund-strategies supabase/fund-strategies

Then have the database fetch and run them: select ingest.run_remote_sql(array['<raw url>']).
"""
import glob, json, os, re, sys

KIND = {"primary": "sponsor", "press": "press", "lp_document": "other"}


def strategy_keys(repo):
    src = open(os.path.join(repo, "lib/directory/strategies.ts"), encoding="utf-8").read()
    keys = set(re.findall(r'\bS\("([a-z_]+)",', src))  # strategy axis only (SECTOR(...) is the other axis)
    return keys


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def main():
    src, outdir = sys.argv[1], sys.argv[2]
    repo = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    keys = strategy_keys(repo)
    os.makedirs(outdir, exist_ok=True)
    for path in sorted(glob.glob(os.path.join(src, "*.json"))):
        d = json.load(open(path, encoding="utf-8"))
        refs, funds, refused = [], [], 0
        for r in d["families"]:
            k = r.get("strategy_key")
            if not k:
                continue
            if k not in keys or not str(r.get("url") or "").startswith("http") or not r.get("evidence"):
                refused += 1
                continue
            ref = {"url": r["url"], "name": r.get("source_name"), "kind": KIND.get(r.get("source_kind"), "other"), "as_of": None,
                   "evidence": r["evidence"][:300], "scope": r.get("scope")}
            i = len(refs)
            refs.append((k, ref))
            funds += [(f["fund_id"], i) for f in r["funds"] if f.get("fund_id")]
        fam = ",\n  ".join(f"({i}, {q(k)}, {q(json.dumps({'strategy_code': [ref]}, ensure_ascii=False))})" for i, (k, ref) in enumerate(refs))
        fu = ",\n  ".join(f"({q(fid)}, {i})" for fid, i in dict(funds).items())
        name = os.path.splitext(os.path.basename(path))[0]
        sql = f"""-- {name}: fund strategies researched for {d.get('lp')} ({d.get('asset_class')}), {d.get('researched_on')}. Generated by
-- supabase/tools/fund_strategies_to_sql.py; re-run freely. {len(refs)} families, {len(dict(funds))} funds, {refused} refused.
with fam(i, code, src) as (values
  {fam}
), fu(fund_id, i) as (values
  {fu}
)
insert into public.fund_details (fund_id, strategy_code, sources)
select fu.fund_id::uuid, fam.code, fam.src::jsonb from fu join fam using (i)
where exists (select 1 from public.funds f where f.id = fu.fund_id::uuid)
on conflict (fund_id) do update set strategy_code = excluded.strategy_code,
  sources = public.fund_details.sources || excluded.sources, updated_at = now();
"""
        open(os.path.join(outdir, name + ".sql"), "w", encoding="utf-8").write(sql)
        print(name, len(refs), "families,", len(dict(funds)), "funds,", refused, "refused")


if __name__ == "__main__":
    main()
